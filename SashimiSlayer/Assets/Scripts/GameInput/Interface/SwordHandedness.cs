namespace GameInput.Interface
{
    /// <summary>
    ///     Handedness type for custom sword controller, for the purposes for inverting controls
    /// </summary>
    public enum SwordHandedness
    {
        /// <summary>
        ///     Right-handed sword controller, i.e right hand is on the sword handle
        /// </summary>
        RightHandedSword,

        /// <summary>
        ///     Left-handed sword controller, i.e left hand is on the sword handle
        /// </summary>
        LeftHandedSword
    }
}